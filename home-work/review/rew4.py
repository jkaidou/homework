count = 0
p = 1 # произведение нужно инициализировать единицей, а не нулём


for i in range(1, 11): # range(1, 10) сделает 9 итераций

    x = int(input())
    if x >= 0: # неотрицательные числа включают в себя ноль (>= 0), а не только строго больше (> 0)

        p = p * x
        count = count + 1

if count > 0:
    print(count) # нужно вывести количество неотрицательных чисел (count), а не последнее число (x)
    print(p)
else:
    print('NO')
